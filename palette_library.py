def palette_by_name(name: str) -> dict[str, str]:
    """Return a palette by its unique display name."""
    return next(palette for palette in PALETTES if palette["name"] == name)


def palette_categories() -> list[str]:
    """Return the category names in their intentional display order."""
    seen: set[str] = set()
    ordered: list[str] = []
    for palette in PALETTES:
        category = palette["category"]
        if category not in seen:
            seen.add(category)
            ordered.append(category)
    return ordered
